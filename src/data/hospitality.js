export function getHospitalityById(idOrSlug) {
  if (!idOrSlug) return hospitalityExperiences[0];
  const normalized = idOrSlug.toLowerCase().trim();
  return hospitalityExperiences.find(
    (item) => item.id.toLowerCase() === normalized || item.slug.toLowerCase() === normalized
  ) || hospitalityExperiences[0];
}

